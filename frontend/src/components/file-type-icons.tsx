/** 按文件名扩展名分派图标（未知扩展名回退通用文件图标）。 */
export function FileTypeIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const ext = name.split(".").pop()?.toLowerCase() ?? "";
  if (ext === "pdf") return <PdfFileIcon className={className} />;
  if (ext === "doc" || ext === "docx")
    return <DocFileIcon className={className} />;
  if (ext === "xls" || ext === "xlsx" || ext === "xlsm" || ext === "csv")
    return <XlsFileIcon className={className} />;
  if (ext === "ppt" || ext === "pptx")
    return <PptFileIcon className={className} />;
  if (ext === "txt") return <TxtFileIcon className={className} />;
  if (
    ext === "png" ||
    ext === "jpg" ||
    ext === "jpeg" ||
    ext === "tif" ||
    ext === "tiff" ||
    ext === "bmp" ||
    ext === "gif"
  )
    return <ImageFileIcon className={className} />;
  return <GenericFileIcon className={className} />;
}
